#!/usr/bin/env python3
"""Generate the pinned equivalence fixture for the merge-arbiter dump walker.

PROVENANCE / one-shot tool (runs OUTSIDE the engine runtime, never in CI):
the engine evaluates the bundled LightGBM v4 text dump with its own local
walker (``vesma.merge_arbiter.LightGbmDump``) — the V3 Δdeps=0 discipline.
This generator pins the walker's exact equivalence against the REAL
lightgbm runtime the model was trained with (lightgbm 4.7.0, the cortex
line's pinned trainer version), so the engine test
``tests/test_merge_arbiter_core.py`` can verify the walker WITHOUT
lightgbm installed.

Rows are deterministic (seed 42): uniform draws over [0, 1]^34 plus
boundary-hugging rows near the observed feature supports (exact 0/1
columns, ±1e-12 perturbations around the 0.5/0.9 score bands) — the
places where a threshold-comparison or float-accumulation drift would
show first.

Usage (READ-ONLY venv use: an explicit interpreter, nothing installed,
PATH untouched):

    <venv-with-lightgbm>/bin/python \
        scripts/generate_merge_arbiter_lgbm_fixture.py \
        --out tests/fixtures/merge_arbiter_lgbm_scores.jsonl

The output's first line is a JSON provenance header (artifact sha256
pin, lightgbm version, seed, row count, numpy version); every following
line is ``{"row": [34 floats], "lgbm": <probability>}`` with full
round-trip float reprs. Re-run only to RE-PIN after a NEW ratified
artifact lands (new sha256 → new fixture file name stays, content
regenerated and re-reviewed).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

from vesma.decision_provider import cortex_feature_set_sha256  # noqa: E402
from vesma.merge_arbiter import (  # noqa: E402
    MERGE_ARTIFACT_DIR,
    MERGE_ARTIFACT_FILE,
    MERGE_ARTIFACT_SHA256,
    MERGE_FEATURE_NAMES,
    LightGbmDump,
)

ARTIFACT_PATH = REPO / "src" / "vesma" / "models" / MERGE_ARTIFACT_DIR / MERGE_ARTIFACT_FILE


def build_rows(n_uniform: int, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    width = len(MERGE_FEATURE_NAMES)
    rows = [rng.random((n_uniform, width))]
    boundary = np.zeros((width * 2, width))
    for c in range(width):
        boundary[2 * c, c] = 0.0
        boundary[2 * c + 1, c] = 1.0
    rows.append(boundary)
    band = rng.random((256, width)) * 1e-6
    half = np.zeros((256, width))
    for r in range(256):
        half[r, rng.integers(0, width)] = 0.0 if rng.random() < 0.5 else 1.0
    rows.append(np.abs(half - band))
    rows.append(np.clip(half + band, 0.0, 1.0))
    return np.concatenate(rows, axis=0).astype(np.float64)


def main(argv: list[str] | None = None) -> int:
    import lightgbm as lgb

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--uniform-rows", type=int, default=400)
    args = ap.parse_args(argv)

    raw = ARTIFACT_PATH.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != MERGE_ARTIFACT_SHA256:
        print(f"REFUSED: bundled artifact sha {digest} != pin {MERGE_ARTIFACT_SHA256}")
        return 2
    doc = json.loads(raw.decode("utf-8"))

    rows = build_rows(args.uniform_rows, args.seed)
    booster = lgb.Booster(model_str=doc["booster_model_string"])
    if booster.num_feature() != len(MERGE_FEATURE_NAMES):
        print("REFUSED: booster width != feature contract")
        return 2
    lgbm_scores = booster.predict(rows)

    walker = LightGbmDump.parse(doc["booster_model_string"], len(MERGE_FEATURE_NAMES))
    walker_scores = np.array([walker.predict_proba(row) for row in rows])

    delta = np.abs(lgbm_scores - walker_scores)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as fh:
        header = {
            "provenance": "merge-arbiter dump-walker equivalence fixture; "
            "generated by scripts/generate_merge_arbiter_lgbm_fixture.py "
            "(one-shot, outside the engine runtime) — see that script's docstring",
            "artifact": MERGE_ARTIFACT_DIR,
            "artifact_sha256": digest,
            "feature_set_sha256": cortex_feature_set_sha256(),
            "lightgbm_version": lgb.__version__,
            "numpy_version": np.__version__,
            "python_version": sys.version.split()[0],
            "machine": platform.machine(),
            "seed": args.seed,
            "rows": int(rows.shape[0]),
            "max_abs_delta": float(delta.max()),
            "tolerance_pinned_by_test": 1e-9,
        }
        fh.write(json.dumps(header, ensure_ascii=False) + "\n")
        for row, score in zip(rows, lgbm_scores, strict=True):
            fh.write(
                json.dumps(
                    {"row": [float(x) for x in row], "lgbm": float(score)},
                    ensure_ascii=False,
                )
                + "\n"
            )
    print(
        f"fixture written: {out} rows={rows.shape[0]} "
        f"max|delta|={delta.max():.3e} lightgbm={lgb.__version__}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
