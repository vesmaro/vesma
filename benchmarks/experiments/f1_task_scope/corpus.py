# ── row / query models ────────────────────────────────────────────────────────


@dataclass(frozen=True)
class CorpusRow:
    """One corpus record exactly as ingested (slug-keyed, fingerprinted)."""

    slug: str
    segment: str  # task_prose | task_code | task_doc | shared | checkpoint | misc | canary
    project: str
    task: str | None  # bare task slug; None = task-less
    title: str
    content: str
    metadata: dict[str, Any] = field(default_factory=dict)
    planted_secret: bool = False  # canaries: expected write-boundary refusal

    @property
    def tags(self) -> list[str]:
        tags = [f"project:{self.project}", f"agent:{AGENT}"]
        if self.task is not None:
            tags.append(f"task:{self.task}")
        return tags


@dataclass(frozen=True)
class GoldQuery:
    """One gold pair: an analyzed query with its birth-declared gold record."""

    qid: str
    text: str
    stratum: str  # t_gold | x_gold | l_neg
    query_class: str  # task | cross (a BIRTH property, §1.3)
    project: str
    current_task: str
    gold_slug: str
    axis: str  # prose | code | doc
    surplus: bool = False  # replacement-pool pair, not analyzed by default
    #: L-neg mixed-phrasing birth property (the G4b falsifiability
    #: repair): True on the activating prose-gold queries whose code-
    #: shaped call token makes the CODE lens narrow. Unused on every
    #: other stratum.
    mixed: bool = False

    @property
    def substratum(self) -> str | None:
        """The L-neg sub-split ("trap" | "mixed"); None outside L-neg.

        The committed, fingerprinted evaluation-scope flag (§8 entry 15):
        the G4b corridor reads the trap family; the mixed-phrasing
        activation-cost measure reads the mixed family. Derived from the
        ``mixed`` birth flag — deterministic, no outcome input.
        """
        if self.stratum != "l_neg":
            return None
        return "mixed" if self.mixed else "trap"


