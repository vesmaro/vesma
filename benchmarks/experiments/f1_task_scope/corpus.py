# ── the build ─────────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class Corpus:
    """The built corpus: rows in ingest order + queries in issue order."""

    rows: tuple[CorpusRow, ...]
    queries: tuple[GoldQuery, ...]
    seed: int
    generator_version: str

    def rows_by_slug(self) -> dict[str, CorpusRow]:
        return {row.slug: row for row in self.rows}

    def analyzed_queries(self) -> tuple[GoldQuery, ...]:
        return tuple(q for q in self.queries if not q.surplus)


def build_corpus() -> Corpus:
    """Generate the full F1 corpus — pure, deterministic, asserted."""
    rng = random.Random(SEED)
    rows: list[CorpusRow] = []
    queries: list[GoldQuery] = []

    # ── task-tagged mass: 8 x (18 prose + 12 code + 15 doc chunks) ──────
    # Per-task layout (12 gold + 3 surplus + 9 adjacent + noise, §3.1 +
    # §3.4 + the §3.5 non-adjacency competition):
    #   prose p00-p05 gold · p06-p11 ADJACENT (same nouns 0-5, different
    #   question) · p12 surplus · p13 foreign-gold (X-gold) · p14-p17 noise;
    #   code  c00-c02 gold · c03-c05 ADJACENT test wrappers (same fns) ·
    #   c06 surplus · c07 foreign-gold · c08-c11 util noise;
    #   doc   chunk 2 of each doc gold · chunk 3 of doc 0 surplus.
    for t_idx, task in enumerate(TASKS):
        project = TASK_PROJECTS[task]
        nouns = _TASK_NOUNS[task]
        quals = rng.sample(_QUALS, len(_QUALS))  # per-task rotation, no repeats
        for p_idx in range(18):
            if p_idx < 6:
                rows.append(
                    _prose_row(
                        slug=f"{task}-p{p_idx:02d}",
                        segment="task_prose",
                        project=project,
                        task=task,
                        noun=nouns[p_idx],
                        qual=quals[p_idx % len(quals)],
                        action=rng.choice(_ACTIONS),
                    )
                )
            elif p_idx < 12:
                rows.append(
                    _adjacent_prose_row(
                        slug=f"{task}-p{p_idx:02d}",
                        project=project,
                        task=task,
                        noun=nouns[p_idx - 6],
                        template=_ADJACENT_TEMPLATES[(t_idx + p_idx) % len(_ADJACENT_TEMPLATES)],
                    )
                )
            elif p_idx == 12:
                rows.append(
                    _prose_row(
                        slug=f"{task}-p12",
                        segment="task_prose",
                        project=project,
                        task=task,
                        noun=nouns[6],
                        qual=quals[6 % len(quals)],
                        action=rng.choice(_ACTIONS),
                    )
                )
            elif p_idx == 13:
                rows.append(
                    _prose_row(
                        slug=f"{task}-p13",
                        segment="task_prose",
                        project=project,
                        task=task,
                        noun=nouns[7],
                        qual=quals[7 % len(quals)],
                        action=rng.choice(_ACTIONS),
                    )
                )
            else:
                rows.append(
                    _noise_prose_row(
                        slug=f"{task}-p{p_idx:02d}",
                        project=project,
                        task=task,
                        noun=nouns[12 + (p_idx - 14)],
                        template=_NOISE_TEMPLATES[(t_idx + p_idx) % len(_NOISE_TEMPLATES)],
                    )
                )
        for c_idx in range(12):
            if c_idx < 3:
                rows.append(
                    _code_row(
                        slug=f"{task}-c{c_idx:02d}",
                        segment="task_code",
                        project=project,
                        task=task,
                        noun=nouns[c_idx],
                    )
                )
            elif c_idx < 6:
                rows.append(
                    _test_code_row(
                        slug=f"{task}-c{c_idx:02d}",
                        project=project,
                        task=task,
                        noun=nouns[c_idx - 3],
                    )
                )
            elif c_idx == 6:
                rows.append(
                    _code_row(
                        slug=f"{task}-c06",
                        segment="task_code",
                        project=project,
                        task=task,
                        noun=nouns[3],
                    )
                )
            elif c_idx == 7:
                rows.append(
                    _code_row(
                        slug=f"{task}-c07",
                        segment="task_code",
                        project=project,
                        task=task,
                        noun=nouns[4],
                    )
                )
            else:
                rows.append(
                    _util_code_row(
                        slug=f"{task}-c{c_idx:02d}",
                        project=project,
                        task=task,
                        noun=nouns[8 + (c_idx - 8)],
                    )
                )
        for doc_idx in range(3):
            for chunk_idx in range(5):
                rows.append(
                    _doc_chunk_row(
                        slug=f"{task}-d{doc_idx}{chunk_idx}",
                        project=project,
                        task=task,
                        doc_idx=doc_idx,
                        chunk_idx=chunk_idx,
                        gold=chunk_idx == 2,
                        qual=quals[(doc_idx + 2) % len(quals)],
                    )
                )
        # T-gold queries: 12 records x 2 phrasings, class = task. Prose
        # records cycle the three difficulty families by GLOBAL index
        # (family = (t_idx*6 + p_idx) % 3 — a birth property).
        for p_idx in range(6):  # prose axis
            _emit_t_pair(
                queries,
                pair=f"ft-{t_idx * 12 + p_idx:03d}",
                task=task,
                project=project,
                slug=f"{task}-p{p_idx:02d}",
                noun=nouns[p_idx],
                axis="prose",
                surplus=False,
                family=(t_idx * 6 + p_idx) % 3,
            )
        for c_idx in range(3):  # code axis (lens-activating queries)
            _emit_t_pair(
                queries,
                pair=f"ft-{t_idx * 12 + 6 + c_idx:03d}",
                task=task,
                project=project,
                slug=f"{task}-c{c_idx:02d}",
                noun=nouns[c_idx],
                axis="code",
                surplus=False,
            )
        for doc_idx in range(3):  # doc axis (heading_path-targeted)
            _emit_t_pair(
                queries,
                pair=f"ft-{t_idx * 12 + 9 + doc_idx:03d}",
                task=task,
                project=project,
                slug=f"{task}-d{doc_idx}2",
                noun=nouns[(doc_idx * 6 + 2) % len(nouns)],
                axis="doc",
                surplus=False,
                doc_idx=doc_idx,
                chunk_idx=2,
            )
        # T-side replacement pool (3 per task): p12 / c06 / doc0 chunk 3.
        _emit_t_pair(
            queries,
            pair=f"ft-s{t_idx * 3:03d}",
            task=task,
            project=project,
            slug=f"{task}-p12",
            noun=nouns[6],
            axis="prose",
            surplus=True,
        )
        _emit_t_pair(
            queries,
            pair=f"ft-s{t_idx * 3 + 1:03d}",
            task=task,
            project=project,
            slug=f"{task}-c06",
            noun=nouns[3],
            axis="code",
            surplus=True,
        )
        _emit_t_pair(
            queries,
            pair=f"ft-s{t_idx * 3 + 2:03d}",
            task=task,
            project=project,
            slug=f"{task}-d03",
            noun=nouns[3 % len(nouns)],
            axis="doc",
            surplus=True,
            doc_idx=0,
            chunk_idx=3,
        )

    # ── shared (task-less) mass: 120 rows ───────────────────────────────
    # 12 X-shared gold + 3 X-shared surplus + 12 L-neg gold + 3 L-neg
    # surplus + 2 chunked docs (10 chunks) + 80 noise.
    for idx in range(12):  # X-shared gold: 6 prose + 6 code
        ask_task = TASKS[_SHARED_ASK[idx]]
        project = TASK_PROJECTS[ask_task]
        if idx < 6:
            rows.append(
                _prose_row(
                    slug=f"sh-p{idx:02d}",
                    segment="shared",
                    project=project,
                    task=None,
                    noun=_SHARED_PROSE_NOUNS[idx],
                    qual=rng.choice(_SHARED_QUALS),
                    action=rng.choice(_ACTIONS),
                )
            )
        else:
            rows.append(
                _code_row(
                    slug=f"sh-c{idx - 6:02d}",
                    segment="shared",
                    project=project,
                    task=None,
                    noun=_SHARED_CODE_NOUNS[idx - 6],
                )
            )
    for idx in range(3):  # X-shared surplus
        ask_task = TASKS[_SHARED_ASK[9 + idx]]  # tasks 5/6/7 — all three project B
        project = TASK_PROJECTS[ask_task]
        rows.append(
            _prose_row(
                slug=f"sh-x{idx:02d}",
                segment="shared",
                project=project,
                task=None,
                noun=_SHARED_PROSE_NOUNS[(6 + idx) % len(_SHARED_PROSE_NOUNS)] + " extension",
                qual=rng.choice(_SHARED_QUALS),
                action=rng.choice(_ACTIONS),
            )
        )
    for k, (_slug_tail, topic, _ph, _pr, mixed) in enumerate(_L_NEG_PAIRS):
        asking = TASKS[k % 8]
        rows.append(_l_neg_row(rng, f"ln-{k:02d}", TASK_PROJECTS[asking], topic, mixed=mixed))
    for k, source in enumerate(_L_NEG_SURPLUS_SOURCE):  # L-neg surplus (trap topics)
        asking = TASKS[(k + 4) % 8]
        topic = _L_NEG_PAIRS[source][1] + " appendix"
        rows.append(_l_neg_row(rng, f"ln-{12 + k:02d}", TASK_PROJECTS[asking], topic, mixed=False))
    for doc_idx in range(2):  # 2 shared chunked docs, 5 chunks each
        project = PROJECT_A if doc_idx == 0 else PROJECT_B
        for chunk_idx in range(5):
            section = _DOC_SECTIONS[chunk_idx]
            noun = _SHARED_PROSE_NOUNS[(doc_idx * 5 + chunk_idx) % len(_SHARED_PROSE_NOUNS)]
            metadata = build_doc_grouping_metadata(
                doc_id=f"shared-doc{doc_idx}",
                chunk_idx=chunk_idx,
                heading_path=["Platform Handbook", section],
            )
            rows.append(
                CorpusRow(
                    slug=f"sh-d{doc_idx}{chunk_idx}",
                    segment="shared",
                    project=project,
                    task=None,
                    title=f"Platform Handbook — {section}",
                    content=(
                        f"## {section}\n\nPlatform handbook working notes: the "
                        f"{noun} section owner curates entries; legacy items "
                        "retire at the quarterly review."
                    ),
                    metadata=metadata,
                )
            )
    for i in range(80):  # shared noise
        rows.append(_misc_row(rng, f"sh-n{i:02d}", "shared", rng.choice((PROJECT_A, PROJECT_B))))

    # ── X-gold queries: 24 shared + 24 foreign, 3 pairs per task ────────
    for idx in range(12):
        ask_task = TASKS[_SHARED_ASK[idx]]
        if idx < 6:
            _emit_x_pair(
                queries,
                f"fx-{idx:03d}",
                f"sh-p{idx:02d}",
                _SHARED_PROSE_NOUNS[idx],
                "prose",
                ask_task,
            )
        else:
            _emit_x_pair(
                queries,
                f"fx-{idx:03d}",
                f"sh-c{idx - 6:02d}",
                _SHARED_CODE_NOUNS[idx - 6],
                "code",
                ask_task,
            )
    for f_idx, (owner_t, ask_t, axis) in enumerate(_FOREIGN_ASK):
        owner, asker = TASKS[owner_t], TASKS[ask_t]
        if axis == "prose":
            slug, noun = f"{owner}-p13", _TASK_NOUNS[owner][7]
        else:
            slug, noun = f"{owner}-c07", _TASK_NOUNS[owner][4]
        _emit_x_pair(queries, f"fx-{12 + f_idx:03d}", slug, noun, axis, asker, owner=owner)
    # X-shared surplus pairs (never analyzed by default)
    for idx in range(3):
        ask_task = TASKS[_SHARED_ASK[9 + idx]]
        noun = _SHARED_PROSE_NOUNS[(6 + idx) % len(_SHARED_PROSE_NOUNS)] + " extension"
        _emit_x_pair(
            queries, f"fx-s{idx:03d}", f"sh-x{idx:02d}", noun, "prose", ask_task, surplus=True
        )

    # ── L-neg queries (cross-class; MIXED composition — the G4b repair) ─
    for k, (_slug_tail, _topic, ph, pr, mixed) in enumerate(_L_NEG_PAIRS):
        asking = TASKS[k % 8]
        for suffix, text in (("ph", ph), ("pr", pr)):
            queries.append(
                GoldQuery(
                    qid=f"fl-{k:03d}-{suffix}",
                    text=text,
                    stratum="l_neg",
                    query_class="cross",
                    project=TASK_PROJECTS[asking],
                    current_task=asking,
                    gold_slug=f"ln-{k:02d}",
                    axis="prose",
                    mixed=mixed,
                )
            )
    for k, source in enumerate(_L_NEG_SURPLUS_SOURCE):  # L-neg surplus pairs
        asking = TASKS[(k + 4) % 8]
        for suffix in ("ph", "pr"):
            queries.append(
                GoldQuery(
                    qid=f"fl-s{k:03d}-{suffix}",
                    text=f"what changed in the {_L_NEG_PAIRS[source][1]} appendix notes?",
                    stratum="l_neg",
                    query_class="cross",
                    project=TASK_PROJECTS[asking],
                    current_task=asking,
                    gold_slug=f"ln-{12 + k:02d}",
                    axis="prose",
                    surplus=True,
                )
            )

    # ── distractor mass: 278 checkpoints + 194 misc + 8 canaries ────────
    # The drowning echo (§3.4): checkpoints speak the TASK vocabulary —
    # each mentions one gold noun of its project's tasks — so the 58%
    # checkpoint mass genuinely contests the lexical space instead of
    # being trivially ignorable (the live-store profile the epic answers).
    project_a_nouns = [n for t in TASKS[:4] for n in _TASK_NOUNS[t][:6]]
    project_b_nouns = [n for t in TASKS[4:] for n in _TASK_NOUNS[t][:6]]
    for i in range(CORPUS_COUNTS["checkpoints"]):
        project = PROJECT_A if i % 2 == 0 else PROJECT_B
        noun = rng.choice(project_a_nouns if project == PROJECT_A else project_b_nouns)
        rows.append(
            CorpusRow(
                slug=f"ck-{i:03d}",
                segment="checkpoint",
                project=project,
                task=None,
                title=f"Checkpoint {i:03d}",
                content=(
                    f"Checkpoint session-{i:03d}: {rng.choice(_CHECKPOINT_STATES)} "
                    f"on the {noun} work; {rng.choice(_CHECKPOINT_NEXT)}."
                ),
            )
        )
    all_nouns = project_a_nouns + project_b_nouns
    for i in range(CORPUS_COUNTS["session_misc"]):
        project = PROJECT_A if i % 3 == 0 else PROJECT_B
        if i % 3 == 1:
            noun = rng.choice(all_nouns)
            content = rng.choice(_MISC_FRAGMENTS) + f" (Touches the {noun} thread.)"
        else:
            content = rng.choice(_MISC_FRAGMENTS)
        rows.append(
            CorpusRow(
                slug=f"ms-{i:03d}",
                segment="misc",
                project=project,
                task=None,
                title="Session note",
                content=content,
            )
        )
    for i, sentinel in enumerate(CANARY_SENTINELS):
        rows.append(
            CorpusRow(
                slug=f"can-{i:02d}",
                segment="canary",
                project=PROJECT_A if i % 2 == 0 else PROJECT_B,
                task=None,
                title=f"Handover snapshot {i:02d}",
                content=_CANARY_TEMPLATE.format(sentinel=sentinel, secret=_canary_secret(rng, i)),
                planted_secret=True,
            )
        )

    corpus = Corpus(
        rows=tuple(rows), queries=tuple(queries), seed=SEED, generator_version=GENERATOR_VERSION
    )
    _assert_corpus(corpus)
    return corpus


# ── query emitters ────────────────────────────────────────────────────────────


def _prose_query_pair(display: str, noun: str, family: int) -> tuple[str, str]:
    """The (ph, pr) phrasings for one prose gold record — a deterministic
    three-family difficulty mix (the §3.5 topical criterion holds in all
    three; only the lexical distance from record to query varies):

    * family 0 (verbatim): the query names the topic outright — the
      easy third, the corpus's findable floor;
    * family 1 (partial): two content words + a question frame;
    * family 2 (scattered): first/last topic words inside an alien
      frame — the realistic hard third where unscoped retrieval must
      genuinely compete (this is what keeps A0 off the ceiling).

    The family is a BIRTH property (global record index mod 3), never
    derived from outcomes.
    """
    words = noun.split()
    first, last = words[0], words[-1]
    if family == 0:
        return (
            f"what did we decide about the {noun}?",
            f"the {display} call on the {noun} — what was the outcome?",
        )
    if family == 1:
        head = " ".join(words[:2])
        return (
            f"the {head} question — what did we settle on?",
            f"where did the {display} work land on {head}?",
        )
    return (
        f"did we ever resolve the {last} concern from the {first} discussion?",
        f"the {first} thread kept circling the {last} limits — what was the final word?",
    )


def _emit_t_pair(
    queries: list[GoldQuery],
    *,
    pair: str,
    task: str,
    project: str,
    slug: str,
    noun: str,
    axis: str,
    surplus: bool,
    doc_idx: int = 0,
    chunk_idx: int = 0,
    family: int = 0,
) -> None:
    """Emit one T-gold (or T-surplus) phrasing pair, class = task."""
    display = TASK_DISPLAY[task]
    if axis == "prose":
        ph, pr = _prose_query_pair(display, noun, family)
    elif axis == "code":
        # Both phrasings carry the call-with-arguments shape so the CODE
        # lens ACTIVATES (§3.1 lens-axis gold) — asserted in _assert_corpus.
        fn = f"handle_{_snake(noun)}"
        ph = f"how does {fn}(event, context) process the {noun}?"
        pr = f"trace the {noun} path — {fn}(event, context) — what does it validate?"
    else:
        doc_title = f"{display} {_DOC_TITLES[doc_idx]}"
        section = _DOC_SECTIONS[chunk_idx]
        ph = f"what does the {doc_title} say under {section} about the {noun}?"
        pr = f"in the {doc_title}, find the {section} guidance on the {noun}"
    for suffix, text in (("ph", ph), ("pr", pr)):
        queries.append(
            GoldQuery(
                qid=f"{pair}-{suffix}",
                text=text,
                stratum="t_gold",
                query_class="task",
                project=project,
                current_task=task,
                gold_slug=slug,
                axis=axis,
                surplus=surplus,
            )
        )


def _emit_x_pair(
    queries: list[GoldQuery],
    pair: str,
    slug: str,
    noun: str,
    axis: str,
    ask_task: str,
    *,
    owner: str | None = None,
    surplus: bool = False,
) -> None:
    """Emit one X-gold phrasing pair, class = cross (the honest switch).

    Foreign-gold pairs (``owner`` given) phrase the question through the
    OWNING task's display label — the §3.2 cross-task world ("what did
    the docs-site task decide about X"); shared pairs use platform
    phrasing (the gold is task-less).
    """
    if axis == "code":
        fn = f"handle_{_snake(noun)}"
        ph = f"what does {fn}(event, context) do with the {noun}?"
        pr = f"the platform {noun} helper — {fn}(event, context) — where is it specified?"
        if owner is not None:
            display = TASK_DISPLAY[owner]
            ph = f"what does the {display} work use {fn}(event, context) for on the {noun}?"
            pr = f"the {display} {noun} helper — {fn}(event, context) — what does it do?"
    elif owner is not None:
        display = TASK_DISPLAY[owner]
        ph = f"what did the {display} work decide about the {noun}?"
        pr = f"the {display} call on the {noun} — what was the outcome?"
    else:
        ph = f"what is the platform rule for the {noun}?"
        pr = f"refresh my memory — the {noun} policy?"
    for suffix, text in (("ph", ph), ("pr", pr)):
        queries.append(
            GoldQuery(
                qid=f"{pair}-{suffix}",
                text=text,
                stratum="x_gold",
                query_class="cross",
                project=TASK_PROJECTS[ask_task],
                current_task=ask_task,
                gold_slug=slug,
                axis=axis,
                surplus=surplus,
            )
        )


# ── fingerprint (§4.2 BLAKE2b-lexical) ────────────────────────────────────────


def _canonical_json(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def _row_fingerprint_view(row: CorpusRow) -> dict[str, Any]:
    return {
        "slug": row.slug,
        "segment": row.segment,
        "project": row.project,
        "task": row.task,
        "title": row.title,
        "content": row.content,
        "metadata": row.metadata,
        "planted_secret": row.planted_secret,
    }


def _query_fingerprint_view(query: GoldQuery) -> dict[str, Any]:
    return {
        "qid": query.qid,
        "text": query.text,
        "stratum": query.stratum,
        "query_class": query.query_class,
        "project": query.project,
        "current_task": query.current_task,
        "gold_slug": query.gold_slug,
        "axis": query.axis,
        "surplus": query.surplus,
        "mixed": query.mixed,
    }


def corpus_fingerprint(corpus: Corpus | None = None) -> str:
    """BLAKE2b-lexical fingerprint over the canonical corpus serialization.

    Covers generator version, seed, TASK_DISPLAY, every row (content +
    tags-defining fields + metadata) and every query with its gold
    assignment — any corpus mutation changes the fingerprint (§4.2).
    """
    built = corpus if corpus is not None else build_corpus()
    payload = {
        "generator": built.generator_version,
        "seed": built.seed,
        "task_display": TASK_DISPLAY,
        "rows": [_row_fingerprint_view(r) for r in built.rows],
        "queries": [_query_fingerprint_view(q) for q in built.queries],
    }
    return hashlib.blake2b(_canonical_json(payload).encode("utf-8"), digest_size=32).hexdigest()


def segment_counts(corpus: Corpus | None = None) -> dict[str, int]:
    """Segment counts of the built corpus (the §3.4 profile)."""
    built = corpus if corpus is not None else build_corpus()
    counts: dict[str, int] = {}
    for row in built.rows:
        counts[row.segment] = counts.get(row.segment, 0) + 1
    return counts


# ── lens activation observation (§8 entry 16 — observed, never asserted) ──────


def lens_activation_observed(
    corpus: Corpus | None = None, queries: tuple[GoldQuery, ...] | None = None
) -> dict[str, int]:
    """Observed CODE-lens activation counts over the (active) analyzed set.

    A run-time FACT of the observing code version — the lens regexes —
    stamped into the manifest's corpus block as ``lens_observed`` and
    pinned per run. Deliberately NOT a build assert (§8 entry 16): a
    future broadened lens that flips a trap query to activating must
    flow through the run as DATA (arm A drops the trap gold → the G4b
    corridor fails in the analysis), never crash the corpus build
    before any arm executes. Current behavior is pinned at the TEST
    layer (``tests/test_f1_task_scope_runner.py``): trap 0 / mixed 8 /
    code-axis 72.

    Families: ``trap_activations`` / ``mixed_activations`` (the L-neg
    substrata — the corridor's red path is trap_activations > 0) and
    ``code_axis_activations`` (the lens-axis gold design, §3.1).
    """
    built = corpus if corpus is not None else build_corpus()
    analyzed = queries if queries is not None else built.analyzed_queries()
    counts = {"trap_activations": 0, "mixed_activations": 0, "code_axis_activations": 0}
    for q in analyzed:
        if not lens_active(Lens.CODE, query=q.text):
            continue
        if q.stratum == "l_neg":
            substratum = q.substratum
            assert substratum is not None  # l_neg by the branch above
            counts[f"{substratum}_activations"] += 1
        elif q.axis == "code":
            counts["code_axis_activations"] += 1
    return counts


# ── audit subsample (§3.5, frozen pre-run) ────────────────────────────────────


def audit_subsample(corpus: Corpus | None = None) -> list[dict[str, str]]:
    """The deterministic blind-audit subsample (the E0 revision-3 rule).

    All ANALYZED pair-ids ranked by sha256(pair-id) hex ascending, top
    ceil(20%) double-annotated. Pairs are arm-stripped by construction:
    each entry carries (pair id, query text, gold slug, gold content)
    only — never arm ids, never run provenance (§4.4).
    """
    built = corpus if corpus is not None else build_corpus()
    rows = built.rows_by_slug()
    pairs = [
        {
            "pair_id": f"{q.qid}::{q.gold_slug}",
            "qid": q.qid,
            "query_text": q.text,
            "gold_slug": q.gold_slug,
            "gold_title": rows[q.gold_slug].title,
            "gold_content": rows[q.gold_slug].content,
        }
        for q in built.analyzed_queries()
    ]
    ranked = sorted(pairs, key=lambda p: hashlib.sha256(p["pair_id"].encode()).hexdigest())
    take = -(-len(ranked) * 20 // 100)  # ceil(20%)
    return ranked[:take]


# ── build-time assertions (fail loud — the corpus, not the test, is fixed) ─────


def _assert_corpus(corpus: Corpus) -> None:
    rows = corpus.rows
    rows_by_slug = corpus.rows_by_slug()
    counts = segment_counts(corpus)

    # §3.4 locked totals.
    expected = {
        "task_prose": 8 * 18,
        "task_code": 8 * 12,
        "task_doc": 8 * 15,
        "shared": 120,
        "checkpoint": CORPUS_COUNTS["checkpoints"],
        "misc": CORPUS_COUNTS["session_misc"],
        "canary": CORPUS_COUNTS["canaries"],
    }
    assert counts == expected, f"segment counts drifted: {counts} != {expected}"
    task_total = counts["task_prose"] + counts["task_code"] + counts["task_doc"]
    assert task_total == CORPUS_COUNTS["task_tagged"]
    assert len(rows) == CORPUS_COUNTS["total"]

    # Unique slugs / qids; V5 tag contract; seed hygiene.
    assert len(rows_by_slug) == len(rows), "duplicate row slugs"
    for row in rows:
        task_tags = [t for t in row.tags if t.startswith("task:")]
        assert len(task_tags) <= 1, f"{row.slug}: multiple task: tags"
        for tag in task_tags:
            assert TASK_TAG_RE.match(tag), f"{row.slug}: bad task tag {tag!r}"
        assert not any(t.startswith(("applyTo:", "mnemos:")) for t in row.tags), (
            f"{row.slug}: seed hygiene violation (applyTo/mnemos tag)"
        )
        if row.segment == "task_doc":
            assert set(DOC_GROUPING_METADATA_FIELDS) <= set(row.metadata)

    # Gold coverage: every analyzed query's gold exists and matches scope.
    analyzed = corpus.analyzed_queries()
    per_stratum: dict[str, int] = {}
    for q in analyzed:
        per_stratum[q.stratum] = per_stratum.get(q.stratum, 0) + 1
        gold = rows_by_slug[q.gold_slug]
        if q.stratum == "t_gold":
            assert q.query_class == "task" and gold.task == q.current_task
        else:
            assert q.query_class == "cross"
        if q.stratum == "x_gold":
            assert gold.task is None or gold.task != q.current_task, (
                f"{q.qid}: foreign/shared gold must not be the current task"
            )
            assert gold.project == q.project, f"{q.qid}: X-gold must share the project"
    assert per_stratum == ANALYZED_COUNTS, f"analyzed counts drifted: {per_stratum}"
    qids = [q.qid for q in corpus.queries]
    assert len(set(qids)) == len(qids), "duplicate qids"

    # Per-task session shape (§2.6b): 24 T-gold + 6 X-gold queries each.
    for task in TASKS:
        t_q = [q for q in analyzed if q.stratum == "t_gold" and q.current_task == task]
        x_q = [q for q in analyzed if q.stratum == "x_gold" and q.current_task == task]
        assert len(t_q) == 24, f"{task}: {len(t_q)} T-gold queries (expected 24)"
        assert len(x_q) == 6, f"{task}: {len(x_q)} X-gold queries (expected 6)"

    # L-neg composition (STRUCTURAL, §8/13): 8 mixed + 16 trap among the
    # analyzed queries. LENS activation itself is NOT asserted here —
    # it is an observed, code-version-dependent fact recorded per run
    # into the manifest (``lens_activation_observed``, §8 entry 16): a
    # broadened lens must flow through the run as DATA (the trap
    # corridor's red path), never crash the corpus build.
    l_neg_analyzed = [q for q in analyzed if q.stratum == "l_neg"]
    l_neg_mixed = [q for q in l_neg_analyzed if q.mixed]
    assert len(l_neg_mixed) == 8, (
        f"L-neg mixed composition drifted: {len(l_neg_mixed)} mixed of "
        f"{len(l_neg_analyzed)} (registered: 8 mixed + 16 trap, §8/13)"
    )
    # The G4b falsifiable arm's gold is cross-class PROSE: the active
    # lens's code-only narrowing can drop it — that is the corridor's
    # measurement path, so the gold must never be code-classified.
    # (detect_profile is the INGEST-side content classifier — corpus
    # shape, not lens behavior.)
    for q in l_neg_mixed:
        gold = rows_by_slug[q.gold_slug]
        assert gold.task is None and gold.segment == "shared", (
            f"{q.qid}: L-neg mixed gold must be a task-less shared (cross-class) row"
        )
        assert detect_profile(gold.content) != "code", (
            f"{q.qid}: L-neg mixed gold must classify prose (a code-typed gold "
            "would be admitted by the lens and the corridor could not measure)"
        )

    # Governance-free corpus (repair 2d): no row may carry a governance-
    # selecting tag. The G4a/V3 probes read the RAW mgr.search order as
    # "the pre-lens order", while _recall_stage under type_boost=True
    # re-ranks governance rows by the x10 boost BEFORE the lens — a
    # governance row would make the probe order diverge from the actual
    # pre-lens order. Seed hygiene already refuses mnemos: tags; this
    # assert names the type_boost equivalence it pins.
    for row in rows:
        gov = GOVERNANCE_TAGS.intersection(row.tags)
        assert not gov, (
            f"{row.slug}: governance tags {sorted(gov)} forbidden — type_boost "
            "re-ranking would break the G4a/V3 probe-order equivalence"
        )

    # Canaries: unique sentinels, each in exactly one row, no echoes.
    for sentinel in CANARY_SENTINELS:
        hits = [r.slug for r in rows if sentinel in r.content.lower()]
        assert len(hits) == 1, f"sentinel {sentinel}: {hits}"
    assert sum(1 for r in rows if r.planted_secret) == CORPUS_COUNTS["canaries"]


