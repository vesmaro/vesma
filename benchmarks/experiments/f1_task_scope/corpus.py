def _snake(noun: str) -> str:
    """noun → snake_case identifier fragment."""
    return re.sub(r"[^a-z0-9]+", "_", noun.lower()).strip("_")


def _canary_secret(rng: random.Random, index: int) -> str:
    """A secret-SHAPED (fake, inert) token — only ever lives in canaries."""
    alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567"
    body = "".join(rng.choice(alphabet) for _ in range(20))
    return f"AKIA{index:02d}{body}"


