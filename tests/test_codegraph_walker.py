PIN_DIR = Path(__file__).parent / "data" / "codegraph_trace_pin"
PIN_FILE = PIN_DIR / "trace_out_default.json"
PIN_TIMESTAMP = "2026-10-06T00:00:00+00:00"


# ── shared fixture tree (the pin recipe, minus the poison extras) ────────────


def _pin_repo(tmp_path: Path, name: str = "pinrepo") -> Path:
    """The pin recipe tree: helper (class + fn), app (imports, subclass,
    call). Deterministic content — the same bytes the committed pin was
    captured on."""
    root = tmp_path / name
    pkg = root / "pkg"
    pkg.mkdir(parents=True)
    (root / "pyproject.toml").write_text("[project]\nname = 'pinrepo'\n", encoding="utf-8")
    (pkg / "__init__.py").write_text("", encoding="utf-8")
    (pkg / "helper.py").write_text(
        "class Base:\n"
        "    def greet(self):\n"
        "        return 'hi'\n"
        "\n"
        "def make_base():\n"
        "    return Base()\n",
        encoding="utf-8",
    )
    (root / "app.py").write_text(
        "from pkg.helper import Base, make_base\n"
        "\n"
        "class Derived(Base):\n"
        "    pass\n"
        "\n"
        "def run():\n"
        "    b = make_base()\n"
        "    b.greet()\n"
        "    return b\n",
        encoding="utf-8",
    )
    return root


# ── unit: fail-closed limits ─────────────────────────────────────────────────


class TestWalkLimitValidation:
    def test_defaults_pass_through(self) -> None:
        assert validate_walk_limits(2, "out", None) == (2, "out", None)
        assert validate_walk_limits(1, "both", []) == (1, "both", None)

    def test_depth_clamp_is_fail_closed(self) -> None:
        for bad in (0, 3, -1, True, "2", 2.0):
            with pytest.raises(WalkLimitError, match="depth must be an integer"):
                validate_walk_limits(bad, "out", None)

    def test_direction_vocabulary(self) -> None:
        for bad in ("OUT", "in/", "bothways", "", None, 3):
            with pytest.raises(WalkLimitError, match="direction must be one of"):
                validate_walk_limits(1, bad, None)
        for ok in ("in", "out", "both"):
            assert validate_walk_limits(1, ok, None)[1] == ok

    def test_kind_filter_vocabulary_and_shape(self) -> None:
        assert validate_walk_limits(1, "out", ["CALLS", "USES"]) == (1, "out", ("CALLS", "USES"))
        # duplicates collapse preserving order; empty = no filter
        assert validate_walk_limits(1, "out", ["USES", "USES"]) == (1, "out", ("USES",))
        # a bare string is a shape bug, not a one-kind walk
        with pytest.raises(WalkLimitError, match="must be a list or tuple"):
            validate_walk_limits(1, "out", "CALLS")
        # a set walks nondeterministically — refused outright
        with pytest.raises(WalkLimitError, match="must be a list or tuple"):
            validate_walk_limits(1, "out", {"CALLS"})  # type: ignore[arg-type]
        with pytest.raises(WalkLimitError, match="edge kind must be one of"):
            validate_walk_limits(1, "out", ["CALLS", "MAGICAL_KIND"])


