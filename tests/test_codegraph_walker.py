# ── caps + project boundary (walker unit, fake store) ────────────────────────


class _TinyEdge:
    def __init__(self, from_id: str, to_id: str, kind: str = "CALLS") -> None:
        self.from_id = from_id
        self.to_id = to_id
        self.kind = kind
        self.weight = 1.0
        self.provenance = "tree-sitter"


class _FakeWalkNode:
    def __init__(self, nid: str, qname: str) -> None:
        self.id = nid
        self.qname = qname
        self.kind = "Function"
        self.path = "f.py"
        self.start_line = 1
        self.end_line = 1


class _FakeWalkStore:
    """A minimal edge source the walker unit tests ride: preloaded
    adjacency (both directions), a GLOBAL get_node (the real store's
    «resolves ids globally» shape — exactly what the prefix guard is
    defending against)."""

    def __init__(self) -> None:
        self.edges: list[_TinyEdge] = []
        self.nodes: dict[str, _FakeWalkNode] = {}

    def add(self, p: str, name: str) -> str:
        nid = f"{len(p)}:{p}#f.py#{name}#1"
        self.nodes[nid] = _FakeWalkNode(nid, f"{p}.{name}")
        return nid

    def add_cross(self, p: str, name: str) -> str:
        """An id that belongs to the SIBLING project (prefix mismatch)."""
        sib = p + "2"
        nid = f"{len(sib)}:{sib}#f.py#{name}#1"
        self.nodes[nid] = _FakeWalkNode(nid, f"{sib}.{name}")
        return nid

    def link(self, a: str, b: str, kind: str = "CALLS") -> None:
        self.edges.append(_TinyEdge(a, b, kind))

    def get_edges(
        self,
        project: str,
        *,
        from_id: str | None = None,
        to_id: str | None = None,
        kind: str | None = None,
        limit: int = 200,
    ) -> list[_TinyEdge]:
        out: list[_TinyEdge] = []
        for e in self.edges:
            if from_id is not None and e.from_id != from_id:
                continue
            if to_id is not None and e.to_id != to_id:
                continue
            if kind is not None and e.kind != kind:
                continue
            out.append(e)
            if len(out) >= limit:
                break
        return out

    def get_node(self, node_id: str) -> _FakeWalkNode | None:
        return self.nodes.get(node_id)


def _sort_key(r: dict[str, object]) -> tuple[object, ...]:
    return (r["depth"], str(r["qname"]))  # type: ignore[return-value]


class TestWalkerCapsAndBoundary:
    def test_fanout_cap_slices_and_flags(self) -> None:
        store = _FakeWalkStore()
        p = "fanproj"
        hub = store.add(p, "hub")
        for i in range(40):  # > 32: the cap must bind
            store.link(hub, store.add(p, f"m{i:02d}"))
        walk = walk_bfs(store, p, hub, store.nodes[hub], depth=1, direction="out")
        assert len([n for n in walk["rows"] if n["depth"] == 1]) == 32
        assert walk["truncated"] is True

    def test_fanout_cap_under_cap_no_flag(self) -> None:
        store = _FakeWalkStore()
        p = "fanproj"
        hub = store.add(p, "hub")
        for i in range(10):
            store.link(hub, store.add(p, f"m{i:02d}"))
        walk = walk_bfs(store, p, hub, store.nodes[hub], depth=1, direction="out")
        assert walk["truncated"] is False

    def test_total_work_cap_bounds_visited(self) -> None:
        store = _FakeWalkStore()
        p = "workproj"
        a = store.add(p, "a")
        b = store.add(p, "b")
        store.link(a, b)
        for i in range(200):
            store.link(a, store.add(p, f"x{i:03d}"), kind="USES")
        walk = walk_bfs(store, p, a, store.nodes[a], depth=2, direction="out")
        rows = walk["rows"]
        assert len(rows) <= 512
        assert walk["truncated"] is True
        # deterministic: the first-level leg (a→b) survives the cap
        assert any(r["qname"] == f"{p}.b" for r in rows)
        assert sorted(rows, key=_sort_key) == rows  # the pinned (depth, qname) sort

    def test_cross_project_endpoint_never_followed(self) -> None:
        """ADR-0038 condition 5 at the WALKER level: the edge to the
        sibling project's id is skipped WHOLE (no row, no node) and the
        walk reports truncated."""
        store = _FakeWalkStore()
        p = "boundproj"
        a = store.add(p, "a")
        foreign = store.add_cross(p, "secret_node")
        store.link(a, foreign, kind="IMPORTS")
        walk = walk_bfs(store, p, a, store.nodes[a], depth=1, direction="out")
        assert walk["truncated"] is True
        assert walk["edges"] == []  # the foreign edge NEVER reported
        assert len(walk["rows"]) == 1  # only the start row
        assert all("2:boundproj" not in r["id"] for r in walk["rows"])  # no leak

    def test_same_project_prefix_length_guard(self) -> None:
        from vesmaro.codegraph.walker import same_project_prefix

        assert same_project_prefix("8:miniproj#a.py#x#1", "miniproj")
        assert not same_project_prefix("9:miniproj2#a.py#x#1", "miniproj")
        assert not same_project_prefix("7:minipro#a.py#x#1", "miniproj")

    def test_in_direction_follows_the_from_endpoint(self) -> None:
        store = _FakeWalkStore()
        p = "inproj"
        a = store.add(p, "a")
        b = store.add(p, "b")
        store.link(b, a)  # b -> a: an INCOMING edge at a
        walk = walk_bfs(store, p, a, store.nodes[a], depth=1, direction="in")
        reached = {r["id"] for r in walk["rows"]}
        assert b in reached
        assert walk["edges"][0]["from"] == b and walk["edges"][0]["to"] == a

    def test_node_row_pg1_shape_no_signature(self) -> None:
        class _N:
            id, qname, kind, path = "x:node", "n", "Function", "a.py"
            start_line, end_line = 1, 2
            signature = "def n(): ..."  # NEVER issued by the row builder

        row = node_row(_N(), 1)
        assert set(row) == {"id", "qname", "kind", "path", "start_line", "end_line", "depth"}
        assert "signature" not in row


