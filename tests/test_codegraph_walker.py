"""ADR-0038 M1: the shared BFS walker (``walker.py``) — direction and
edge-kind filters, fail-closed limits, the project id prefix guard, and
the trace_path byte-pin.

Contract pins:

* one walker: ``trace_path`` rides :func:`walker.walk_bfs` with the
  ``out`` default — its answers are byte-identical to the
  pre-extraction tool (existing corpus unchanged + a JSON pin of a live
  request, ``tests/data/codegraph_trace_pin/trace_out_default.json``);
* ``direction`` (``in``/``both``) and ``edge_kinds`` are the NEW M1
  surface — every leg is a point query (no recursive CTE), the BOTH
  expansion walks the incoming leg first (deterministic), and the kind
  filter rides per-kind capped queries (OR-semantics, no overlap);
* the fail-closed limits (ADR-0038 condition 3): a depth outside
  ``[1, 2]``, an unknown direction, a bare-string kind list, a set (an
  unordered container), a bool depth — every breach is a REFUSAL
  before any store access, never a silently different walk;
* the project boundary at the followed endpoint (condition 5): an id
  whose project prefix does not match is NOT followed — the walk sets
  ``truncated`` (the default-direction answers stay byte-identical
  because real indexes never produce cross-project edges);
* caps: fanout 32 (the ``+1`` probe slices + flags), total work 512 —
  the same numbers the ``trace`` schema card reports;
* PG1 row shape: node rows carry shapes only — no ``signature``, no
  literal content (condition 4).

Pin regeneration discipline: the committed JSON was captured by
indexing the pin recipe tree (a copy of the tool suite's mini_repo
content minus its test/longlines/longname/secret extras — exactly the
``_pin_repo`` builder below, deterministic), stamping
``last_indexed:8:pinproj = 2026-10-06T00:00:00+00:00`` in the sidecar
meta and issuing ``trace_path('pinproj', 'Derived', depth=2)``
(defaults: out, unfiltered, 3200 tokens). The pin is regenerated by the
same recipe, never hand-edited — a byte diff is a finding either way.
"""

